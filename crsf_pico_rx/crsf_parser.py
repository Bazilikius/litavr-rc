    def __init__(self):
        self._buffer = bytearray()
        self._channels = [992] * 16

    def _crc8(self, data):
        crc = 0
        for b in data:
            crc = self.CRC8_TAB[crc ^ b]
        return crc

    def process_byte(self, byte):
        self._buffer.append(byte)
        if len(self._buffer) > self.CRSF_MAX_PACKET_LEN:
            # Shift buffer left to keep size bounded
            self._buffer = self._buffer[1:]

        # Process while buffer has enough data for header
        while len(self._buffer) >= 3:
            sync = self._buffer[0]
            # Valid sync: Broadcast (0x00) or Device addresses
            if sync not in [0xC8, 0xEA, 0xEE, 0xEC, 0xEB, 0x00]:
                self._buffer = self._buffer[1:]
                continue

            length = self._buffer[1]
            if length < 2 or length > 62:
                self._buffer = self._buffer[1:]
                continue

            if len(self._buffer) < (length + 2):
                # Need more data
                return False

            # Frame is fully received in buffer
            packet_type = self._buffer[2]
            expected_crc = self._buffer[length + 1]

            # Calculate CRC over payload: type + payload data (length - 1 bytes)
            actual_crc = self._crc8(self._buffer[2:length+1])

            if actual_crc != expected_crc:
                # CRC mismatch, slide window and try next index
                self._buffer = self._buffer[1:]
                continue

            # CRC check passed!
            success = False
            if packet_type == 0x16: # RC_CHANNELS_PACKED
                self._unpack_channels(self._buffer[3:length+1])
                success = True

            # Consume processed frame
            self._buffer = self._buffer[length + 2:]
            if success:
                return True

        return False

    def _unpack_channels(self, payload):
        # Unpack 16 channels from 22-byte payload, each 11 bits
        self._channels[0]  = ((payload[0]       | payload[1]  << 8) & 0x07FF)
        self._channels[1]  = ((payload[1]  >> 3 | payload[2]  << 5) & 0x07FF)
        self._channels[2]  = ((payload[2]  >> 6 | payload[3]  << 2 | payload[4] << 10) & 0x07FF)
        self._channels[3]  = ((payload[4]  >> 1 | payload[5]  << 7) & 0x07FF)
        self._channels[4]  = ((payload[5]  >> 4 | payload[6]  << 4) & 0x07FF)
        self._channels[5]  = ((payload[6]  >> 7 | payload[7]  << 1 | payload[8] << 9) & 0x07FF)
        self._channels[6]  = ((payload[8]  >> 2 | payload[9]  << 6) & 0x07FF)
        self._channels[7]  = ((payload[9]  >> 5 | payload[10] << 3) & 0x07FF)
        self._channels[8]  = ((payload[11]      | payload[12] << 8) & 0x07FF)
        self._channels[9]  = ((payload[12] >> 3 | payload[13] << 5) & 0x07FF)
        self._channels[10] = ((payload[13] >> 6 | payload[14] << 2 | payload[15] << 10) & 0x07FF)
        self._channels[11] = ((payload[15] >> 1 | payload[16] << 7) & 0x07FF)
        self._channels[12] = ((payload[16] >> 4 | payload[17] << 4) & 0x07FF)
        self._channels[13] = ((payload[17] >> 7 | payload[18] << 1 | payload[19] << 9) & 0x07FF)
        self._channels[14] = ((payload[19] >> 2 | payload[20] << 6) & 0x07FF)
        self._channels[15] = ((payload[20] >> 5 | payload[21] << 3) & 0x07FF)

    def get_channel(self, index):
        if 0 <= index < 16:
            return self._channels[index]
        return 0
